  // Значок: 'знак' | 'знак:цвет' | data:-картинка; def — значок, если пусто или знак не найден
  function parse(v) {
    const [g, c] = String(v || '').split(':');
    return { g, c };
  }
  function svg(v, def = 'macro') {
    const { g, c } = parse(v);
    const x = BY.get(g);
    if (!x) return Icons.svg(def);
    const [a, b] = COLORS[c] || COLORS[x.color] || COLORS.orange;
    return Icons.tile(a, b, x.glyph);
  }
  function el(v, def = 'macro') {
    const s = document.createElement('span');
    s.className = 'mp-icon';
    if (String(v || '').startsWith('data:')) {
      const img = Object.assign(document.createElement('img'), { src: v, alt: '' });
      img.style.cssText = 'width:100%;height:100%;object-fit:contain;border-radius:22%';
      s.append(img);
    } else s.innerHTML = svg(v, def);
    return s;
  }
